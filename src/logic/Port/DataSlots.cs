    // 控制台写缓存槽时同步写真值(反之亦然), 返回 null 表示该槽不是缓存.
    public static string? Mirror(int slot) => slot switch
    {
        7 => "influencePRC",
        28 => "empires[0].relations",
        29 => "empires[1].relations",
        _ => null,
    };

    // 真值字段 → 对应缓存槽, 找不到返回 -1
