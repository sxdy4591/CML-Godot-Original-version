    public static int Count => Names.Length;

    public static string Name(int slot) => Names[slot];

    public static bool Known(int slot) => Names[slot].Length > 0;

    // 显示单位: data 是 ×10 内部单位(50 = 5.0), 日期/编号类槽是原值
    public static string Text(int slot, int value) => Known(slot) && Raw(slot) ? value.ToString() : Fixed(value);

    // 原值显示(不除 10)的槽
    public static bool Raw(int slot) => slot is 19 or 20 or 21 or 82 or 47 or 105 or 108;

