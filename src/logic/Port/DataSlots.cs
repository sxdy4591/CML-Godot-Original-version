    {
        "influencePRC" => 7,
        "empires[0].relations" => 28,
        "empires[1].relations" => 29,
        _ => -1,
    };

    static string Fixed(int value)
    {
        var a = System.Math.Abs(value);
        return (value < 0 ? "-" : "") + a / 10 + "." + a % 10;
    }

